  static List<Destination> getByRegion(String region) {
    if (region == 'All') return destinations;
    return destinations.where((d) => d.region.toLowerCase().contains(region.toLowerCase())).toList();
  }

  static Destination getById(String id) {
    return destinations.firstWhere(
      (d) => d.id == id,
      orElse: () => destinations.first,
    );
  }
